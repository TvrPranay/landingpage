-- Teklozy core schema for Supabase (PostgreSQL + Supabase Auth).
-- Run in Supabase SQL Editor or with Supabase CLI migrations.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Learner',
  avatar_url text,
  current_level integer not null default 1 check (current_level between 1 and 10),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.learning_paths (
  id text primary key,
  title text not null,
  description text not null default '',
  icon text not null default 'book-open',
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.levels (
  id bigint generated by default as identity primary key,
  level_number integer not null unique check (level_number between 1 and 10),
  title text not null,
  description text not null default '',
  required_xp integer not null default 1000,
  is_published boolean not null default true
);

create table if not exists public.modules (
  id bigint generated by default as identity primary key,
  path_id text references public.learning_paths(id) on delete set null,
  level_id bigint references public.levels(id) on delete set null,
  title text not null,
  description text not null default '',
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  module_id bigint references public.modules(id) on delete cascade,
  title text not null,
  description text not null default '',
  lesson_type text not null default 'Reading' check (lesson_type in ('Reading','Visual','Video')),
  duration_minutes integer not null default 5 check (duration_minutes > 0),
  content jsonb not null default '{}'::jsonb,
  video_url text,
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed boolean not null default false,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(user_id, lesson_id)
);

create table if not exists public.user_stats (
  user_id uuid primary key references auth.users(id) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  current_streak integer not null default 0 check (current_streak >= 0),
  longest_streak integer not null default 0 check (longest_streak >= 0),
  last_activity_date date,
  updated_at timestamptz not null default now()
);


-- Persist the learner's first career-path choice. A single row per user prevents
-- the selection screen from appearing again on subsequent visits.
create table if not exists public.user_path_selection (
  user_id uuid primary key references auth.users(id) on delete cascade,
  path_id text not null references public.learning_paths(id),
  selected_at timestamptz not null default now()
);

-- Store quiz attempts for lesson-level knowledge checks.
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint references public.lessons(id) on delete set null,
  score integer not null check (score >= 0),
  total_questions integer not null check (total_questions > 0),
  answers jsonb not null default '{}'::jsonb,
  attempted_at timestamptz not null default now()
);

create table if not exists public.user_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  note text not null default '',
  updated_at timestamptz not null default now(),
  unique(user_id, lesson_id)
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  image_url text,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  starts_at timestamptz not null,
  location text,
  registration_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

-- Create learner profile and stats automatically after signup.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  insert into public.user_stats(user_id) values (new.id) on conflict (user_id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Award XP once when a lesson is completed for the first time.
create or replace function public.award_lesson_xp(lesson_key bigint)
returns integer language plpgsql security definer set search_path = public as $$
declare
  was_completed boolean := false;
  current_xp integer := 0;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select coalesce(completed, false) into was_completed
    from public.lesson_progress
    where user_id = auth.uid() and lesson_id = lesson_key;
  insert into public.lesson_progress(user_id, lesson_id, completed, completed_at)
  values (auth.uid(), lesson_key, true, now())
  on conflict (user_id, lesson_id) do update
    set completed = true,
        completed_at = coalesce(public.lesson_progress.completed_at, now()),
        updated_at = now();
  insert into public.user_stats(user_id, xp, updated_at)
  values (auth.uid(), case when coalesce(was_completed, false) then 0 else 125 end, now())
  on conflict (user_id) do update
    set xp = public.user_stats.xp + case when coalesce(was_completed, false) then 0 else 125 end,
        updated_at = now();
  select xp into current_xp from public.user_stats where user_id = auth.uid();
  return current_xp;
end;
$$;

